import assert from 'node:assert/strict';
import path from 'node:path';

export async function testForum({ seller, buyer, pageIn, browser, go, at, fill, clickText, bodyContains, intercept, base, api, run, output }) {
  const title = `图书馆学习经验 ${run}`;
  const content = '第一段：提前预约，带好校园卡。\n\n第二段：安静自习。<script>window.forumInjected = true</script>';
  const guest = await pageIn(await browser.createBrowserContext());
  await go(guest, '/forum/new');
  await at(guest, '/login');
  assert(guest.url().includes('redirect='));
  await go(guest, '/forum/999999999');
  await bodyContains(guest, '帖子不存在或已删除');
  assert.equal(await guest.$('.forum-body'), null);

  await go(seller, '/forum/new');
  await fill(seller, '[aria-label="帖子标题"]', title);
  await fill(seller, '[aria-label="帖子正文"]', content);
  await seller.select('[aria-label="帖子分类"]', '学习');
  await (await seller.$('[aria-label="帖子封面"]')).uploadFile(path.resolve('public/assets/images/forum_library.png'));
  await seller.waitForFunction(() => document.querySelector('.forum-cover')?.naturalWidth > 0);
  await clickText(seller, 'button', '存草稿');
  await bodyContains(seller, '草稿已保存');
  await seller.reload({ waitUntil: 'networkidle0' });
  assert.equal(await seller.$eval('[aria-label="帖子正文"]', e => e.value), content);
  assert.equal(await seller.$eval('[aria-label="帖子分类"]', e => e.value), '学习');
  const resetPublish = await intercept(seller, r => r.method() === 'POST' && r.url().endsWith('/api/forum/posts'));
  await clickText(seller, 'button', '发布帖子');
  await bodyContains(seller, '网络连接失败');
  assert.equal((await (await fetch(`${api}/forum/posts?keyword=${encodeURIComponent(title)}`)).json()).data.total, 0);
  assert.equal(await seller.$eval('[aria-label="帖子正文"]', e => e.value), content);
  await resetPublish();
  await clickText(seller, 'button', '发布帖子');
  await seller.waitForFunction(() => /^\/forum\/\d+$/.test(location.pathname));
  const postId = Number(new URL(seller.url()).pathname.split('/').pop());
  await bodyContains(seller, title);
  const readPost = async () => (await (await fetch(`${api}/forum/posts/${postId}`)).json()).data;
  assert.equal((await readPost()).content, content);
  await seller.reload({ waitUntil: 'networkidle0' });
  assert.equal(await seller.$eval('.forum-body', e => e.textContent), content);
  assert.equal(await seller.evaluate(() => Boolean(window.forumInjected)), false);
  assert.equal(await seller.$eval('.forum-cover', e => e.getAttribute('src').startsWith('/api/uploads/')), true);
  console.log('PASS forum auth, missing-post 404, cover upload, draft, failed-write retry and durable plain-text post');

  await clickText(seller, 'a', '编辑帖子');
  await at(seller, `/forum/${postId}/edit`);
  const editedTitle = `${title}修订`;
  await fill(seller, '[aria-label="帖子标题"]', editedTitle);
  await clickText(seller, 'button', '保存修改');
  await at(seller, `/forum/${postId}`);
  await bodyContains(seller, editedTitle);
  await go(buyer, `/forum/${postId}/edit`);
  await bodyContains(buyer, '只能编辑自己发布的帖子');
  assert.equal(await buyer.$('[aria-label="帖子标题"]'), null);
  await go(buyer, '/forum');
  await fill(buyer, '[aria-label="搜索帖子"]', editedTitle);
  await clickText(buyer, '.forum-search button', '搜索');
  await bodyContains(buyer, editedTitle);
  await clickText(buyer, '.forum-tabs button', '生活');
  await bodyContains(buyer, '没有找到帖子');
  await clickText(buyer, '.forum-tabs button', '学习');
  await buyer.waitForSelector('.forum-post-card');
  await buyer.click('.forum-post-card');
  await at(buyer, `/forum/${postId}`);
  await bodyContains(buyer, editedTitle);
  assert.equal(await buyer.$('a[href$="/edit"]'), null);
  await go(seller, '/my-posts');
  await bodyContains(seller, editedTitle);
  await go(seller, '/');
  await seller.waitForFunction(t => document.querySelector('.forum-section')?.textContent.includes(t), {}, editedTitle);
  await seller.click('.forum-section .forum-post-card');
  await at(seller, `/forum/${postId}`);
  console.log('PASS forum owner editing, cross-user edit rejection, category/search filters, own posts and real homepage entry');

  const resetComment = await intercept(buyer, r => r.method() === 'POST' && r.url().endsWith(`/forum/posts/${postId}/comments`));
  await fill(buyer, '[aria-label="评论内容"]', '谢谢分享，已经预约好了。');
  await clickText(buyer, 'button', '发布评论');
  await bodyContains(buyer, '网络连接失败');
  assert.equal((await readPost()).comment_count, 0);
  assert.equal(await buyer.$eval('[aria-label="评论内容"]', e => e.value), '谢谢分享，已经预约好了。');
  await resetComment();
  await clickText(buyer, 'button', '发布评论');
  await bodyContains(buyer, '评论已发布并保存');
  await buyer.reload({ waitUntil: 'networkidle0' });
  await bodyContains(buyer, '谢谢分享，已经预约好了。');
  await clickText(buyer, 'button', '编辑评论');
  await fill(buyer, '[aria-label="修改评论内容"]', '修订：预约成功，感谢提醒！');
  await clickText(buyer, 'button', '保存评论');
  await bodyContains(buyer, '评论已更新');
  await seller.reload({ waitUntil: 'networkidle0' });
  await bodyContains(seller, '修订：预约成功，感谢提醒！');
  assert.equal(await seller.$('.forum-comment .forum-actions'), null);
  await clickText(buyer, 'button', '删除评论');
  await clickText(buyer, 'dialog[open] button', '取消');
  assert.equal((await readPost()).comment_count, 1);
  await clickText(buyer, 'button', '删除评论');
  await clickText(buyer, 'dialog[open] button', '确认删除');
  await bodyContains(buyer, '评论已删除');
  assert.equal((await readPost()).comment_count, 0);
  await fill(buyer, '[aria-label="评论内容"]', '备份恢复验收用的真实评论');
  await clickText(buyer, 'button', '发布评论');
  await bodyContains(buyer, '评论已发布并保存');
  assert.equal((await readPost()).comment_count, 1);
  console.log('PASS forum cross-account comments, failed-write retention, durable edit and confirmed deletion');

  await go(seller, '/forum/new');
  await fill(seller, '[aria-label="帖子标题"]', `删除验收 ${run}`);
  await fill(seller, '[aria-label="帖子正文"]', '临时帖用于验证删除与评论级联。');
  await clickText(seller, 'button', '发布帖子');
  await seller.waitForFunction(() => /^\/forum\/\d+$/.test(location.pathname));
  const deleteId = Number(new URL(seller.url()).pathname.split('/').pop());
  await bodyContains(seller, '临时帖用于验证删除与评论级联。');
  await fill(seller, '[aria-label="评论内容"]', '这条评论随帖子一同删除。');
  await clickText(seller, 'button', '发布评论');
  await bodyContains(seller, '评论已发布并保存');
  await clickText(seller, 'button', '删除帖子');
  await bodyContains(seller, '帖子和下面的所有评论');
  await clickText(seller, 'dialog[open] button', '取消');
  assert.equal((await fetch(`${api}/forum/posts/${deleteId}`)).status, 200);
  await clickText(seller, 'button', '删除帖子');
  await clickText(seller, 'dialog[open] button', '确认删除');
  await at(seller, '/my-posts');
  assert.equal((await fetch(`${api}/forum/posts/${deleteId}/comments`)).status, 404);
  const resetList = await intercept(guest, r => r.method() === 'GET' && r.url().includes('/api/forum/posts?'));
  await go(guest, '/forum');
  await bodyContains(guest, '网络连接失败');
  assert.equal(await guest.$('.forum-post-card'), null);
  await resetList();
  await clickText(guest, '.request-state button', '重试');
  await guest.waitForSelector('.forum-post-card');
  for (const width of [375, 390, 440]) {
    await seller.setViewport({ width, height: 812 });
    for (const route of ['/forum', `/forum/${postId}`, `/forum/${postId}/edit`]) {
      await go(seller, route);
      assert.equal(await seller.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('.forum-page').scrollWidth > document.querySelector('.forum-page').clientWidth), false, `Forum overflow at ${width}: ${route}`);
    }
  }
  await go(seller, '/forum');
  await seller.screenshot({ path: path.join(output, 'forum-list-mobile.png') });
  await go(seller, `/forum/${postId}`);
  await seller.screenshot({ path: path.join(output, 'forum-detail-mobile.png') });
  console.log('PASS forum delete confirmation/cascade, offline retry and 375/390/440px layouts');
  await guest.close();
}
